#!/usr/bin/env node
'use strict';
// Writes THIRD_PARTY_NOTICES.md: every package shipped in the desktop and Android apps (production
// dependencies from the lockfiles), each with its licence and copyright lines, then one full copy of each
// licence's text. Run it after changing dependencies: `node scripts/third-party.js`.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const APPS = [['Desktop app', '.'], ['Android app', 'mobile']];
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

function packages(dir) {
  const lock = JSON.parse(fs.readFileSync(path.join(ROOT, dir, 'package-lock.json'), 'utf8')).packages;
  const out = new Map();
  for (const [key, p] of Object.entries(lock)) {
    if (!key || p.dev || p.devOptional || p.link) continue;
    const name = p.name || key.slice(key.lastIndexOf('node_modules/') + 13);
    const at = path.join(ROOT, dir, key);
    const id = `${name}@${p.version}`;
    if (!out.has(id)) out.set(id, { name, version: p.version, license: p.license || 'see package', at });
  }
  return [...out.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function licenceText(at) {
  try {
    const f = fs.readdirSync(at).find((n) => LICENSE_FILE.test(n));
    return f ? fs.readFileSync(path.join(at, f), 'utf8').replace(/\r\n/g, '\n').trim() : '';
  } catch { return ''; }
}
const COPYRIGHT = /^\s*(copyright\b|\(c\)|©)/i;
const copyrights = (text) => [...new Set(text.split('\n').filter((l) => COPYRIGHT.test(l)).map((l) => l.trim()))];
// the licence's own wording, without whose copyright it is (so one copy covers every package)
const body = (text) => text.split('\n').filter((l) => !COPYRIGHT.test(l)).join('\n').replace(/^\s*(the )?(mit|isc) licen[cs]e.*\n/i, '').trim();

const lines = ['# Third-party notices', '',
  'WakeUp includes the open-source software below. Each is used under its own licence. The full text of each',
  'licence is at the end of this file. Generated by `scripts/third-party.js` from the lockfiles.', '',
  'The desktop app is built on [Electron](https://www.electronjs.org/) (MIT), which includes Chromium and other',
  'components; their notices ship with the app as `LICENSES.chromium.html` and `LICENSE`.', '',
  '## Fonts', '', '- **Inter** by The Inter Project Authors, under the SIL Open Font License 1.1 (`src/ui/fonts/OFL.txt`).', ''];
const texts = new Map(); // licence id -> one representative text

for (const [title, dir] of APPS) {
  const list = packages(dir);
  lines.push(`## ${title} (${list.length} packages)`, '');
  for (const p of list) {
    const text = licenceText(p.at);
    const who = copyrights(text);
    lines.push(`- **${p.name}** ${p.version}: ${p.license}${who.length ? `. ${who.slice(0, 3).join('; ')}` : ''}`);
    if (text && !texts.has(p.license) && body(text).length > 200) texts.set(p.license, { from: p.name, text: body(text) });
  }
  lines.push('');
}

lines.push('## Licence texts', '');
for (const [id, { from, text }] of [...texts].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`### ${id}`, '', `(as included with ${from}; the copyright holders are listed above)`, '', '```text', text.replace(/```/g, "'''"), '```', '');
}

fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), `${lines.join('\n').trim()}\n`);
console.log(`THIRD_PARTY_NOTICES.md: ${APPS.map(([, d]) => packages(d).length).join(' + ')} packages, ${texts.size} licence texts`);
