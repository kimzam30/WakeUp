// Builds src/lib/jsqr-source.ts: jsQR (Apache-2.0, node_modules/jsqr) minified into a string. The attendance-QR
// scanner injects it into a meeting's web page, where it reads frames from the shared screen (src/lib/qr-scan.ts).
// Run after updating jsqr: node scripts/gen-jsqr.js
const fs = require('fs');
const path = require('path');
const { minify } = require('terser');

(async () => {
  const src = fs.readFileSync(require.resolve('jsqr/dist/jsQR.js'), 'utf8');
  const out = await minify(src, { compress: true, mangle: true, format: { comments: false } });
  const head = '// Generated by scripts/gen-jsqr.js from jsqr (Apache-2.0, https://github.com/cozmo/jsQR). Do not edit.\n';
  fs.writeFileSync(path.join(__dirname, '../src/lib/jsqr-source.ts'), `${head}const JSQR_SOURCE = ${JSON.stringify(out.code)};\nexport default JSQR_SOURCE;\n`);
  console.log('jsqr-source.ts', out.code.length, 'chars');
})();
