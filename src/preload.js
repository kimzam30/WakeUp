'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const listen = (ch) => (fn) => ipcRenderer.on(ch, (_e, v) => fn(v));
// only WakeUp's own pages get the bridge, never a website that somehow ended up in one of its windows
if (location.protocol === 'file:' && /\/ui\/(index|pop|link)\.html$/.test(location.pathname)) contextBridge.exposeInMainWorld('hub', {
  init: () => ipcRenderer.invoke('init'),
  onStatus: listen('status'),
  onUnread: listen('unread'),
  onCmd: listen('cmd'),
  onFocused: listen('focused'),
  onSettings: listen('settings'),
  onDownload: listen('download'),
  onFound: listen('found'),
  onPlanner: listen('planner'),
  onNotice: listen('notice'),
  onSync: listen('sync'),
  sync: (action) => ipcRenderer.invoke('sync', action),
  onUpdate: listen('update'),
  update: (action) => ipcRenderer.invoke('update', action),
  commit: (layout) => ipcRenderer.send('commit', layout),
  bounds: (b) => ipcRenderer.send('bounds', b),
  cover: (on) => ipcRenderer.send('cover', on),
  focusView: (id) => ipcRenderer.send('focus-view', id),
  retry: (id) => ipcRenderer.send('retry', id),
  retryFailed: () => ipcRenderer.send('retry-failed'),
  nav: (id, action) => ipcRenderer.send('nav', { id, action }),
  tab: (id, action, arg) => ipcRenderer.send('tab', { id, action, arg }),
  tabs: () => ipcRenderer.invoke('tabs'),
  onTabs: listen('tabs'),
  find: (id, text, forward, start) => ipcRenderer.send('find', { id, text, forward, start }),
  findBar: (id, open) => ipcRenderer.send('find-bar', { id, open }),
  setSettings: (patch) => ipcRenderer.invoke('settings-set', patch),
  pickFolder: (what) => ipcRenderer.invoke('pick-folder', what),
  clearAppData: (id) => ipcRenderer.send('clear-app-data', id),
  download: (id, action) => ipcRenderer.send('download', { id, action }),
  viewDownload: (id, how) => ipcRenderer.send('view-download', { id, how }),
  app: (action) => ipcRenderer.send('app', action),
  // timetable + tasks
  planner: () => ipcRenderer.invoke('init').then((s) => s.planner),
  setPlanner: (patch) => ipcRenderer.invoke('planner-set', patch),
  signIns: (action, data) => ipcRenderer.invoke('signins', action, data),
  scanQr: (id) => ipcRenderer.invoke('qr-scan', id),
  exportPlanner: () => ipcRenderer.invoke('planner-export'),
  importPlanner: () => ipcRenderer.invoke('planner-import'),
  openLink: (url) => ipcRenderer.send('open-link', url),
  // link windows: their bar, dragging them back in, and docking
  linkInit: () => ipcRenderer.invoke('link-init'),
  onLink: listen('link'),
  linkAction: (action) => ipcRenderer.send('link-action', action),
  linkDrag: (on) => ipcRenderer.send('link-drag', !!on),
  dockLink: (token) => ipcRenderer.invoke('dock-link', token),
  // screenshots
  capture: (kind, id, rect) => ipcRenderer.invoke('capture', { kind, id, rect }),
  saveShot: (dataUrl) => ipcRenderer.invoke('save-shot', dataUrl),
  shotAction: (id, action, how) => ipcRenderer.send('shot-action', { id, action, how }),
});
